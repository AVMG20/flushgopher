func write(t testing.TB, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func reg(typeExpr, name string) string {
	return fmt.Sprintf("<?php\nuse Magento\\Framework\\Component\\ComponentRegistrar;\nComponentRegistrar::register(%s, '%s', __DIR__);\n", typeExpr, name)
}

