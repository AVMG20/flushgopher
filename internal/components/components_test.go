func TestDiscover(t *testing.T) {
	base := fakeStore(t)
	comps, warnings, err := DiscoverWithWarnings(base)
	if err != nil {
		t.Fatal(err)
	}
	v := func(p string) string { return filepath.Join(base, p) }
	want := []Component{
		{Language, "magento_nl_nl", v("vendor/magento/language-nl_nl")},
		{Library, "magento/framework", v("vendor/magento/framework")},
		{Module, "Acme_Linked", v("external/linked-module")},
		{Module, "Acme_Local", v("app/code/Acme/Local")},
		{Module, "Acme_One", v("vendor/acme/multi/One")},
		{Module, "Acme_SubA", v("vendor/acme/super/app/code/Acme/SubA")},
		{Module, "Acme_SubB", v("vendor/acme/super/app/code/Acme/SubB")},
		{Module, "Acme_Two", v("vendor/acme/multi/Two")},
		{Module, "Magento_Catalog", v("vendor/magento/module-catalog")},
		{Theme, "adminhtml/Acme/admin", v("app/design/adminhtml/Acme/admin")},
		{Theme, "frontend/Acme/shop", v("app/design/frontend/Acme/shop")},
		{Theme, "frontend/Hyva/default", v("vendor/hyva/theme/src")},
		{Theme, "frontend/Magento/luma", v("vendor/magento/theme-frontend-luma")},
	}
	if !reflect.DeepEqual(comps, want) {
		t.Errorf("got:\n%s\nwant:\n%s", dump(comps), dump(want))
	}
	joined := strings.Join(warnings, "\n")
	if !strings.Contains(joined, "module-missing") || !strings.Contains(joined, "acme/broken") {
		t.Errorf("expected warnings for missing and broken registration files, got %q", warnings)
	}
}

func TestDiscoverCustomGloblistAndNoNonComposer(t *testing.T) {
	base := fakeStore(t)
	write(t, filepath.Join(base, "app/etc/registration_globlist.php"), "<?php\nreturn ['app/code/*/*/registration.php'];\n")
	comps, err := Discover(base)
	if err != nil {
		t.Fatal(err)
	}
	for _, c := range comps {
		if c.Name == "frontend/Acme/shop" {
			t.Errorf("custom globlist ignored: %v", c)
		}
	}
	// Without NonComposerComponentRegistration.php in autoload_files, app/code is not scanned.
	af := filepath.Join(base, "vendor/composer/autoload_files.php")
	data, _ := os.ReadFile(af)
	write(t, af, strings.Replace(string(data), "NonComposerComponentRegistration.php", "Other.php", 1))
	comps, err = Discover(base)
	if err != nil {
		t.Fatal(err)
	}
	for _, c := range comps {
		if strings.HasPrefix(c.Name, "Acme_L") {
			t.Errorf("app/code scanned without NonComposerComponentRegistration: %v", c)
		}
	}
}

